// Generate per-glyph SVG outline paths for the hero's inked line so it can
// be stroke-drawn like a drafter lettering a sheet. Re-run if the headline
// text changes:
//   node scripts/gen-headline-paths.mjs
import * as fontkit from "fontkit";
import { writeFileSync } from "node:fs";

const TEXT = "that run themselves.";
// Space Grotesk has no italic, so the accent line gets a drafted oblique:
// a 12° skew baked into the outlines, the way engineers slant lettering.
const AXES = { wght: 500 };
const SKEW = Math.tan((12 * Math.PI) / 180); // x' = x + SKEW * y (y-up)
const OUT = "components/headlinePaths.ts";

const vf = fontkit.openSync("scripts/.fonts/SpaceGrotesk-VF.ttf");
const font = vf.getVariation(AXES);
const upm = font.unitsPerEm;

const run = font.layout(TEXT);
let x = 0;
const glyphs = [];
const bbox = { minX: Infinity, minY: Infinity, maxX: -Infinity, maxY: -Infinity };
for (let i = 0; i < run.glyphs.length; i++) {
  const g = run.glyphs[i];
  const pos = run.positions[i];
  if (g.path.commands.length) {
    const gx = x + pos.xOffset;
    const gy = pos.yOffset;
    const b = g.path.bbox; // capture before transform (may mutate the path)
    // bake oblique + position + y-flip into the path data so the SVG needs no
    // transform attributes (the print stylesheet nukes transforms globally).
    // Oblique first (y-up space): [1, 0, SKEW, 1], then flip+place.
    const d = g.path
      .transform(1, 0, SKEW, 1, 0, 0)
      .transform(1, 0, 0, -1, gx, -gy)
      .toSVG();
    glyphs.push({ d });
    // skewed extents: x gains SKEW*y at both y extremes
    const xs = [
      b.minX + SKEW * b.minY,
      b.minX + SKEW * b.maxY,
      b.maxX + SKEW * b.minY,
      b.maxX + SKEW * b.maxY,
    ];
    bbox.minX = Math.min(bbox.minX, Math.min(...xs) + gx);
    bbox.maxX = Math.max(bbox.maxX, Math.max(...xs) + gx);
    bbox.minY = Math.min(bbox.minY, b.minY + gy);
    bbox.maxY = Math.max(bbox.maxY, b.maxY + gy);
  }
  x += pos.xAdvance;
}

const data = {
  text: TEXT,
  upm,
  ascent: font.ascent,
  descent: font.descent, // negative
  width: x,
  bbox, // tight ink bounds of the whole run, font units (y-up)
  glyphs,
};

writeFileSync(
  OUT,
  `// Generated by scripts/gen-headline-paths.mjs — do not edit by hand.
// "${TEXT}" in Space Grotesk (wght ${AXES.wght}) with a 12° drafted oblique.
// Path data is y-down with glyph positions baked in; bbox is y-up font units.
export interface HeadlineGlyph { d: string }
export interface HeadlineBBox { minX: number; minY: number; maxX: number; maxY: number }
export interface HeadlineData {
  text: string; upm: number; ascent: number; descent: number;
  width: number; bbox: HeadlineBBox; glyphs: HeadlineGlyph[];
}
const data: HeadlineData = ${JSON.stringify(data)};
export default data;
`
);
console.log(
  `wrote ${OUT}: ${glyphs.length} glyphs, width ${x}u, upm ${upm}, ascent ${font.ascent}, descent ${font.descent}`
);
